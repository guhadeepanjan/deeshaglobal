  function rankCountries(results, p) {
    var rows = results.map(function (r) {
      var counts = { likely: 0, borderline: 0, offer: 0, notyet: 0, unavailable: 0 };
      r.routes.forEach(function (x) { counts[x.eval.verdict]++; });
      var score = counts.likely * 3 + counts.borderline * 1.5 + counts.offer * 1;
      var why;
      var firstLikely = r.routes.filter(function (x) { return x.eval.verdict === "likely"; })[0];
      var firstOffer = r.routes.filter(function (x) { return x.eval.verdict === "offer"; })[0];
      var firstBord = r.routes.filter(function (x) { return x.eval.verdict === "borderline"; })[0];
      if (firstLikely) why = counts.likely + " route" + (counts.likely > 1 ? "s" : "") + " look" + (counts.likely > 1 ? "" : "s") + " likely eligible on your answers — starting with " + shortName(firstLikely.route.name) + ".";
      else if (firstOffer) why = "Real options exist, but they start with an employer offer — for example " + shortName(firstOffer.route.name) + ".";
      else if (firstBord) why = "Close but not clean yet: " + shortName(firstBord.route.name) + " is borderline — " + (firstBord.eval.gaps[0] ? lcFirst(firstBord.eval.gaps[0]) : "see the route card") + "";
      else why = "No route currently fits your answers — the cards below say exactly what would have to change.";
      if (r.country === "UAE" && p.goal === "settle") why += " Note: no PR path exists here, which conflicts with a settle-permanently goal.";
      return { country: r.country, score: score, counts: counts, why: why, note: COUNTRY_NOTES[r.country] || "" };
    });
    rows.sort(function (a, b) { return b.score - a.score; });
    return rows;
  }

  function shortName(n) { return String(n).split("—")[0].split("(")[0].trim(); }
  function lcFirst(s) { return s ? s.charAt(0).toLowerCase() + s.slice(1) : s; }


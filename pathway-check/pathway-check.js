  /* ---------- language requirement parsing (dataset text) ---------- */
  function langRequirement(text) {
    if (!text) return { type: "none" };
    var s = String(text);
    if (/UNVERIFIED/i.test(s)) return { type: "unverified", label: s };
    var clb = s.match(/CLB\s*(\d+)/g);
    if (clb) {
      var mx = 0;
      clb.forEach(function (x) { mx = Math.max(mx, parseInt(x.replace(/\D/g, ""), 10)); });
      var map = { 4: 4.5, 5: 5.0, 6: 5.5, 7: 6.0, 8: 6.5, 9: 7.0, 10: 7.5 };
      return { type: "ielts", req: map[mx] || 6.0, label: s };
    }
    var im = s.match(/IELTS[^0-9]*(\d+(?:\.\d+)?)/i);
    if (im) return { type: "ielts", req: parseFloat(im[1]), label: s };
    if (/CEFR\)|B2/i.test(s)) return { type: "ielts", req: 6.0, label: s };
    return { type: "none" };
  }


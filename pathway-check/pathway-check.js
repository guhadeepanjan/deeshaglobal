  function render(data, p) {
    var results = data.countries.map(function (c) {
      return {
        country: c.country,
        routes: c.routes.map(function (r) { return { route: r, eval: evaluate(r, c.country, p), p: p }; })
      };
    });
    var ranked = rankCountries(results, p);
    var byCountry = {};
    results.forEach(function (r) { byCountry[r.country] = r; });

    /* Layer 1 */
    var l1 = ranked.map(function (row, i) {
      return '<div class="pc-country"><div class="pc-rank">' + (i + 1) + '</div><div><h3>' + esc(row.country) + "</h3><p>" + esc(row.why) + "</p>" +
        (row.note ? '<p class="pc-cnote">' + esc(row.note) + "</p>" : "") +
        '<p class="pc-counts">' + row.counts.likely + " likely · " + row.counts.borderline + " borderline · " + row.counts.offer + " need an offer · " + row.counts.notyet + " not yet · " + row.counts.unavailable + " unavailable</p></div></div>";
    }).join("");
    document.getElementById("pc-layer1").innerHTML = l1;

    /* Layer 2 — summary cards on screen */
    var order = ranked.map(function (r) { return r.country; });
    var l2 = order.map(function (cn) {
      var r = byCountry[cn];
      var avail = r.routes.filter(function (x) { return x.eval.verdict !== "unavailable"; });
      var unavail = r.routes.filter(function (x) { return x.eval.verdict === "unavailable"; });
      var sorted = avail.concat(unavail);
      return '<section class="pc-country-block"><h3>' + esc(cn) + "</h3>" + sorted.map(function (x) { return cardHtml(x, false); }).join("") + "</section>";
    }).join("");
    document.getElementById("pc-layer2").innerHTML = l2;

    /* Full report (locked until email) */
    var rep = order.map(function (cn) {
      var r = byCountry[cn];
      return '<section class="pc-country-block"><h3>' + esc(cn) + "</h3>" + r.routes.map(function (x) { return cardHtml(x, true); }).join("") + "</section>";
    }).join("");
    document.getElementById("pc-report-cards").innerHTML = rep;

    document.getElementById("pc-results").style.display = "block";
    document.getElementById("pc-gate").style.display = "block";
    document.getElementById("pc-results").scrollIntoView({ behavior: "smooth", block: "start" });
    return { ranked: ranked, results: results };
  }


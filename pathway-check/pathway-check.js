  function rankCountries(results, p) {
    var rows = results.map(function (r) {
      var counts = { likely: 0, borderline: 0, offer: 0, notyet: 0, unavailable: 0 };
      r.routes.forEach(function (x) { counts[x.eval.verdict]++; });
      var score = counts.likely * 3 + counts.borderline * 1.5 + counts.offer * 1;
      var why;
      var firstLikely = r.routes.filter(function (x) { return x.eval.verdict === "likely"; })[0];
      var firstOffer = r.routes.filter(function (x) { return x.eval.verdict === "offer"; })[0];
      var firstBord = r.routes.filter(function (x) { return x.eval.verdict === "borderline"; })[0];
      if (firstLikely) why = counts.likely + " route" + (counts.likely > 1 ? "s" : "") + " appear" + (counts.likely > 1 ? "" : "s") + " likely eligible on your answers — beginning with " + shortName(firstLikely.route.name) + ".";
      else if (firstOffer) why = "Real options exist here, but each begins with an employer offer — " + shortName(firstOffer.route.name) + ", for example.";
      else if (firstBord) why = "Close, but not yet settled: " + shortName(firstBord.route.name) + " is borderline — " + (firstBord.eval.gaps[0] ? lcFirst(firstBord.eval.gaps[0]) : "see the route review") + "";
      else why = "No route in this country currently fits your answers. The detailed review sets out what would have to change.";
      if (r.country === "UAE" && p.goal === "settle") why += " Note: there is no permanent residence in the UAE, which conflicts with a goal of settling permanently.";
      return { country: r.country, score: score, counts: counts, why: why, note: COUNTRY_NOTES[r.country] || "" };
    });
    rows.sort(function (a, b) { return b.score - a.score; });
    return rows;
  }

